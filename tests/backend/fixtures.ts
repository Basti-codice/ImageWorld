// Generates a realistic fixture library in a temp dir (images via sharp, EXIF via exiftool, video via ffmpeg).
import { execFileSync } from 'node:child_process';
import { copyFileSync, mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import sharp from 'sharp';
import { getExifTool, shutdownExifTool } from '../../src/main/metadata';
import { makeHeic } from './heic-fixture';

export interface Fixtures {
  root: string;
  dir: (...p: string[]) => string;
  cleanup: () => Promise<void>;
}

const gps = (lat: number, lon: number) => ({
  GPSLatitude: Math.abs(lat), GPSLatitudeRef: lat >= 0 ? 'N' : 'S',
  GPSLongitude: Math.abs(lon), GPSLongitudeRef: lon >= 0 ? 'E' : 'W',
});

export function tempDir(prefix = 'iw-test-'): string {
  return mkdtempSync(join(tmpdir(), prefix));
}

async function solid(file: string, w: number, h: number, color: string, fmt: 'jpeg' | 'png' | 'webp' | 'gif' | 'tiff' | 'avif' = 'jpeg') {
  // a coloured block in the top-left corner makes orientation visible in thumbnails
  const img = sharp({ create: { width: w, height: h, channels: 3, background: color } })
    .composite([{ input: { create: { width: Math.round(w / 4), height: Math.round(h / 4), channels: 3, background: '#ffffff' } }, left: 0, top: 0 }]);
  await img[fmt]().toFile(file);
}

export async function buildFixtures(): Promise<Fixtures> {
  const root = tempDir('iw-fixtures-');
  const d = (...p: string[]) => join(root, ...p);
  mkdirSync(d('trip', 'sub'), { recursive: true });
  mkdirSync(d('.hidden'), { recursive: true });
  mkdirSync(d('$RECYCLE.BIN'), { recursive: true });
  const et = getExifTool();

  // landscape with full EXIF (Paris)
  await solid(d('trip', 'paris.jpg'), 640, 480, '#3366aa');
  await et.write(d('trip', 'paris.jpg'), {
    DateTimeOriginal: '2023:05:01 14:30:00', ...gps(48.8566, 2.3522), GPSAltitude: 35, GPSAltitudeRef: 0,
    Make: 'Apple', Model: 'iPhone 15 Pro', LensModel: 'iPhone 15 Pro back camera 6.86mm f/1.78',
    ISO: 125, FNumber: 1.78, ExposureTime: '1/250', FocalLength: 6.86,
  }, ['-overwrite_original']);

  // portrait stored as landscape + orientation 6 (Munich, southern/western-hemisphere-safe sign test elsewhere)
  await solid(d('trip', 'portrait.jpg'), 300, 200, '#aa3333');
  await et.write(d('trip', 'portrait.jpg'), { 'Orientation#': 6, DateTimeOriginal: '2022:12:24 18:00:00', ...gps(48.1374, 11.5755), Make: 'NIKON CORPORATION', Model: 'NIKON D850' }, ['-overwrite_original']);

  // southern + western hemisphere (Rio)
  await solid(d('trip', 'rio.jpg'), 320, 240, '#33aa66');
  await et.write(d('trip', 'rio.jpg'), { DateTimeOriginal: '2021:02:03 04:05:06', ...gps(-22.9068, -43.1729) }, ['-overwrite_original']);

  // no EXIF at all, date only in file name
  await solid(d('trip', 'IMG_20190704_101500.jpg'), 200, 200, '#888888');
  // null island + garbage
  await solid(d('trip', 'nullisland.jpg'), 200, 100, '#222222');
  await et.write(d('trip', 'nullisland.jpg'), { DateTimeOriginal: '2020:01:01 00:00:00', GPSLatitude: 0, GPSLongitude: 0, GPSLatitudeRef: 'N', GPSLongitudeRef: 'E' }, ['-overwrite_original']);

  // other raster formats
  await solid(d('trip', 'sub', 'tokyo.png'), 200, 150, '#33aa33', 'png');
  await et.write(d('trip', 'sub', 'tokyo.png'), { DateTimeOriginal: '2022:01:02 03:04:05', ...gps(35.6762, 139.6503) }, ['-overwrite_original']);
  await solid(d('trip', 'sub', 'anim.gif'), 120, 90, '#aa33aa', 'gif');
  await solid(d('trip', 'sub', 'pic.webp'), 120, 90, '#33aaaa', 'webp');
  await solid(d('trip', 'sub', 'pic.avif'), 128, 96, '#aaaa33', 'avif');
  await solid(d('trip', 'sub', 'scan.tif'), 160, 120, '#555599', 'tiff');
  // BMP: 24 bit, 40x30
  {
    const w = 40, h = 30, rowSize = Math.ceil((w * 3) / 4) * 4;
    const buf = Buffer.alloc(54 + rowSize * h);
    buf.write('BM', 0); buf.writeUInt32LE(buf.length, 2); buf.writeUInt32LE(54, 10);
    buf.writeUInt32LE(40, 14); buf.writeInt32LE(w, 18); buf.writeInt32LE(h, 22); buf.writeUInt16LE(1, 26); buf.writeUInt16LE(24, 28);
    for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) { const o = 54 + y * rowSize + x * 3; buf[o] = 0x30; buf[o + 1] = 0x80; buf[o + 2] = 0xd0; }
    writeFileSync(d('trip', 'sub', 'old.bmp'), buf);
  }

  // video with GPS (Tokyo) – generated by the system ffmpeg
  execFileSync('ffmpeg', ['-y', '-loglevel', 'error', '-f', 'lavfi', '-i', 'testsrc=size=320x240:rate=15:duration=2', '-pix_fmt', 'yuv420p',
    '-metadata', 'location=+35.6762+139.6503+40.0/', '-metadata', 'creation_time=2022-08-09T10:11:12Z', d('trip', 'clip.mp4')]);

  // fake RAW: a DNG container with embedded preview JPEG + orientation 6
  await solid(d('prev.jpg'), 640, 480, '#e0a030');
  await sharp({ create: { width: 800, height: 600, channels: 3, background: '#101010' } }).tiff().toFile(d('raw.tif'));
  copyFileSync(d('raw.tif'), d('trip', 'raw.dng'));
  rmSync(d('raw.tif'));
  await et.write(d('trip', 'raw.dng'), { DNGVersion: '1.4.0.0', Make: 'Canon', Model: 'Canon EOS R5', 'Orientation#': 6, DateTimeOriginal: '2021:07:08 09:10:11' },
    [`-PreviewImage<=${d('prev.jpg')}`, '-overwrite_original']);
  rmSync(d('prev.jpg'));

  // HEIC (handmade HEVC-in-HEIF) with an irot box
  makeHeic(d('trip', 'photo.heic'), 256, 192, 1);
  try {
    await et.write(d('trip', 'photo.heic'), { DateTimeOriginal: '2020:08:15 12:00:00', ...gps(52.52, 13.405) }, ['-overwrite_original']);
  } catch { /* some exiftool builds cannot write HEIC – the file is still valid */ }

  // junk that must be ignored / fail gracefully
  writeFileSync(d('trip', 'notes.txt'), 'not a photo');
  writeFileSync(d('.hidden', 'secret.jpg'), 'x');
  writeFileSync(d('$RECYCLE.BIN', 'trash.jpg'), 'x');
  writeFileSync(d('trip', 'broken.jpg'), Buffer.from('this is definitely not a jpeg'));

  return {
    root,
    dir: d,
    cleanup: async () => {
      await shutdownExifTool();
      rmSync(root, { recursive: true, force: true });
    },
  };
}

/** number of media files buildFixtures() creates that the scanner must index (no txt / hidden / recycle) */
export const FIXTURE_MEDIA_COUNT = 15;
